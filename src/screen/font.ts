/** A character's rows ("#" lit), or the question mark's for one the panel does not have. */
export function glyph(ch: string): string[] {
  return (TABLE[ch] ?? TABLE["?"]).split("|");
}

/** Pixels across `text` at `scale`, with one column (times the scale) between letters, or `gap` pixels when given, and none after the last. */
export function textWidth(text: string, scale = 1, gap = 0): number {
  if (!text) return 0;
  const chars = [...text];
  return chars.reduce((sum, ch) => sum + glyph(ch)[0].length, 0) * scale + (chars.length - 1) * (gap || scale);
}

