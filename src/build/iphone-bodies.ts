// The iPhones, one row per body. Every number is read from Apple's dimensional drawing of that model unless its comment says otherwise: the Accessory Design Guidelines of 2017 and 2020 for the iPhones before the
// 12, and the sheets at developer.apple.com/accessories for the rest. The sizes are the drawing's, a hundredth finer than the spec sheets'.
//
// What a drawing does not dimension is measured from it or from Apple's picture of that model, and the row says so. Across on the back runs from the left as seen from behind. A front camera's or a sensor's radius
// is its keepout at the surface where the drawing gives no other. A body's corner radius is read from the corner's profile, where the drawing lists one, as the last value before the straight.
import type { EdgePart, SlabBody } from "./slab-body.ts";

const speakerRow = (from: number, to: number, count: number): number[] => Array.from({ length: count }, (_, i) => Math.round((from + ((to - from) * i) / (count - 1)) * 100) / 100);
const down = (start: number, length: number, kind: EdgePart[0] = "switch"): EdgePart => [kind, Math.round((start + length / 2) * 100) / 100, length];
/** The foot of a phone: a row of holes, a screw, the socket, a screw, a row of holes, as the sheet gives them. */
const foot = (from: number, to: number, count: number, screw1: number, screw2: number, from2: number, to2: number, count2: number): number[] => [...speakerRow(from, to, count), screw1, screw2, ...speakerRow(from2, to2, count2)];

